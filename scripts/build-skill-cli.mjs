#!/usr/bin/env node
// Bundles src/skillCli/mdc.ts into the standalone helper that ships with the
// Claude skill, and embeds it as a string constant for skill.ts to install.
//
// Two outputs, deliberately:
//   out/skill/mdc.mjs          — runnable during development / tests
//   src/skillCli/generated.ts  — the string the extension actually installs
//
// The generated constant exists because the skill installer has always been
// a pure string-writing module (no vscode import, no runtime file reads), and
// keeping that shape means the CLI ships wherever the extension ships. The
// alternative — reading out/skill/mdc.mjs at install time — would silently
// install nothing if packaging ever missed the file.
//
// `src/test/skillCli.test.ts` re-runs this bundle and fails if the committed
// generated.ts is stale, so editing mdc.ts without rebuilding is caught in CI
// rather than shipped.

import * as esbuild from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SHEBANG = "#!/usr/bin/env node\n";

/** Bundle the CLI and return its full source text (shebang included). */
export async function buildSkillCli() {
  const result = await esbuild.build({
    entryPoints: [path.join(root, "src/skillCli/mdc.ts")],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    write: false,
    legalComments: "none",
    // No minify: this lands in the user's home directory, where a human may
    // reasonably want to read what they are about to run.
  });
  return SHEBANG + result.outputFiles[0].text;
}

function generatedModule(content) {
  return `// AUTO-GENERATED by scripts/build-skill-cli.mjs — do not edit.
// Regenerate with: npm run bundle:skill-cli
//
// This is src/skillCli/mdc.ts bundled with its imports (the real format
// engine and integrity checker) into a dependency-free ESM script, embedded
// as a string so the skill installer can write it to ~/.claude/skills/.

export const CLI_SCRIPT_CONTENT = ${JSON.stringify(content)};
`;
}

const content = await buildSkillCli();

mkdirSync(path.join(root, "out/skill"), { recursive: true });
writeFileSync(path.join(root, "out/skill/mdc.mjs"), content, "utf8");
writeFileSync(path.join(root, "src/skillCli/generated.ts"), generatedModule(content), "utf8");

process.stdout.write(
  `bundle:skill-cli → out/skill/mdc.mjs + src/skillCli/generated.ts (${content.length} bytes)\n`,
);
